/**
 * The install path: scaffold into an adopter's repository what nothing upstream
 * covers, which is the GitHub Actions half of the loop.
 *
 * Since the reference callers became real files under test,
 * `examples/callers/` is the source and this **copies** rather than generates.
 * That is the smaller job and the better one: a generator is a second
 * description of a caller, and the first release after it drifts is one where an
 * adopter installs something the suite has never seen.
 *
 * The one thing in a caller that is per-repo is the **pin**, which should be
 * this package's own version at the time `init` runs, and it is written through
 * the same rewrite the release performs (`shared/pins.ts`).
 *
 * And it **updates on a re-run** rather than refusing. The commonest reason to
 * run this twice is a new release; a scaffolder that says "remove it first" is
 * one an adopter works around by hand, which is how the pin went four releases
 * stale in the repository this loop was piloted on.
 *
 * So a re-run is **not** a second copy. A caller is what an adopter owns
 * (CONTEXT.md) — their trigger, their permissions, the `with:` inputs
 * `docs/ADOPTING.md` §4 ships commented out for them to enable, a job id they
 * renamed, a second job in the same file — and a re-run that rewrote the file
 * from the reference would revert every one of those and report it as
 * `updated`. A pnpm repository that had set `setup: pnpm i --frozen-lockfile`
 * would then die at `npm ci` with nothing saying why: the failure class this
 * whole command exists to remove, recreated by the command itself.
 *
 * Therefore:
 *
 * - a caller **already installed** has its pin moved *in its own text* and
 *   nothing else touched;
 * - a caller **not installed** is copied from the reference, pinned — but only
 *   when this is a first run. Once any caller is installed, the subset an
 *   adopter took is a decision, and a re-run reports what is absent rather than
 *   writing a `pull_request_target` workflow nobody asked for back into their
 *   tree.
 *
 * What drifts as a result — a `permissions:` line a later release added — is
 * exactly what `doctor` names, with the fix, on the same footing as everything
 * else it will not silently change for you.
 */

/**
 * The reference callers, resolved the way a runner resolves its prompt —
 * relative to this module, so the same path works in a checkout and in the
 * tarball `scripts/copy-assets.ts` builds.
 */
const REFERENCE_DIR = path.join(import.meta.dirname, "..", "examples", "callers");

/** The prompt for the judgement work, and the marker that says we wrote it. */
const SETUP_TEMPLATE = path.join(import.meta.dirname, "SETUP.md");
const SETUP_FILE = "SETUP.md";

/**
 * What the template's first line says once substituted. Specific enough that an
 * adopter's own `SETUP.md` cannot match it by accident, and visible enough that
 * deleting the line is how you opt out of having it rewritten.
 */
const setupMarker = (): string => `generated by ${PACKAGE_NAME} init`;

/**
 * The reference filename an adopter gets when nothing is installed yet. The
 * prefix exists so a caller does not collide by filename with the reusable half
 * it calls; `readInstalledCallers` recognises a caller by what it calls, so a
 * rename survives a re-run.
 */
const CALLER_PREFIX = "agent-";

/**
 * A label exactly as it has to be created: the name a workflow filters on, and
 * the colour and description `docs/ADOPTING.md` §3 gives it.
 *
 * Both tables below are a **second copy** of that §3 block — this one feeds
 * `SETUP.md`'s create commands and `doctor`'s missing-label errors, and the doc
 * is what a human reads. Held in step by `tests/agent-cli.test.ts`, which parses
 * §3 and compares, in the spirit of `PIN` in `tests/workflows.test.ts`: a rename
 * or a recolour in either place fails the build by name rather than leaving
 * `init` scaffolding one string and a workflow filtering on another.
 */
export interface LabelSpec {
  readonly name: string;
  readonly color: string;
  readonly description: string;
}

