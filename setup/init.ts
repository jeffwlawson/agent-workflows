/** Those of them an installation of exactly these workflows should be told about. */
export const advisoryLabelSpecsFor = (workflows: readonly string[]): readonly LabelSpec[] =>
  workflows.flatMap((workflow) => ADVISORY_LABELS[workflow] ?? []);

/**
 * A label exactly as it has to be created, as one line of shell.
 *
 * One definition, used by both halves: `SETUP.md` tells an adopter to run these
 * and `doctor` offers them as the fix for a label that does not exist. Only the
 * name decides anything at run time, so a second copy of the form would not
 * break a loop — it would just leave a repository that followed `doctor`'s
 * advice carrying five differently-coloured, undescribed labels from one that
 * ran `init`, and `docs/ADOPTING.md` §3 unable to be right about both.
 */
export const labelCommand = ({ name, color, description }: LabelSpec): string =>
  `gh label create "${name}" --color ${color} --description "${description}"`;

export interface InitChange {
  /**
   * Repo-relative, forward-slashed; or, for the one change that is not a file,
   * `POLICY_CHANGE`.
   */
  readonly file: string;
  /**
   * `kept` is the one that is a **refusal**: a file this will not write over,
   * or a caller an adopter does not have and this will not add for them. It
   * always carries the note saying which.
   */
  readonly action: "created" | "updated" | "unchanged" | "kept" | "deleted";
  /** Why — mandatory on `kept`, since a refusal nobody can read is a silence. */
  readonly note?: string;
}

export interface InitOptions {
  /** The adopting repository's root. */
  readonly dir: string;
  /**
   * Where the Actions policy is read and written: `livePolicySurface(dir)`
   * from the CLI, a stand-in from the tests. Required rather than defaulted to
   * the live one, so no call can reach a real GitHub without naming it; a
   * default made every test calling `init` spawn `gh` against whatever
   * repository the environment named.
   */
  readonly github: PolicySurface;
  /**
   * Where the labels are read and written: `liveLabelSurface(dir)` from the
   * CLI, a stand-in from the tests. Required for the same reason as `github`.
   */
  readonly labels: LabelSurface;
}

/** How the policy step names itself in the list of changes. */
export const POLICY_CHANGE = `Actions policy "${POLICY_NAME}"`;

const referenceFiles = (): readonly string[] =>
  fs
    .readdirSync(REFERENCE_DIR)
    .filter((entry) => entry.endsWith(".yml"))
    .sort();

/**
 * Read back what is about to be written and check the one coupling that has no
 * runtime symptom: `self-check` must name the job it sits in.
 *
 * The pin is a text edit against a file this does not own, and this reads the
 * result the way GitHub would rather than trusting that a regex was applied. A
 * `self-check` naming some other job is a review that waits for itself for 15 of
 * its 20 minutes and then reviews on degraded evidence — precisely the class of
 * defect that must not reach an adopter's disk, and the one thing here that no
 * test in *their* repository could catch.
 */
const assertCoupled = (text: string, file: string): void => {
  const written = callersIn(text, PACKAGE_NAME, file)[0];

  if (written === undefined) {
    throw new Error(`Refusing to write ${file}: it declares no job calling ${PACKAGE_NAME}.`);
  }
  // The same rule `doctor` rules on, from the same function rather than
  // written out twice: the whole name, byte for byte, since a `self-check`
  // naming the wrong called job — or the right two halves with the spaces
  // around the slash left out — is as invisible as one naming the wrong caller
  // job.
  if (!selfCheckMatches(written)) {
    throw new Error(
      `Refusing to write ${file}: \`self-check\` would be ${JSON.stringify(written.selfCheck)}, ` +
        `but the check run the \`${written.jobId}\` job produces is named ` +
        `\`${selfCheckFor(written)}\` — \`<calling job's name> / <called job's name>\` — so the ` +
        `wait would ` +
        `not recognise its own and would wait for itself.`,
    );
  }
};

/** What a write did, without writing the same bytes twice. */
const put = (full: string, text: string): "created" | "updated" | "unchanged" => {
  if (!fs.existsSync(full)) {
    fs.mkdirSync(path.dirname(full), { recursive: true });
    fs.writeFileSync(full, text);
    return "created";
  }
  if (fs.readFileSync(full, "utf8") === text) return "unchanged";
  fs.writeFileSync(full, text);
  return "updated";
};

const renderSetup = (workflows: readonly string[], callers: readonly string[]): string => {
  const labels = labelSpecsFor(workflows).map(labelCommand);
  const advisory = advisoryLabelSpecsFor(workflows).map(labelCommand);

  // Absent entirely rather than present and empty, placeholder line included:
  // a heading over nothing reads as a step somebody forgot to finish, and a
  // repository that declined the filing caller has no step here to finish.
  //
  // Uncounted, and that is deliberate rather than clumsy prose: the list is
  // per caller, so a repository that took some of them gets some of these, and
  // a number written here would be right for the installation this file was
  // authored against and wrong for the next one.
  const advisoryBlock =
    advisory.length === 0
      ? ""
      : [
          "",
          "**More labels, for the callers listed at the top of this file.** None of them is a",
          "transition and the check at the bottom demands none of them — but a review then marks",
          "nothing, a filed issue arrives unlabelled (invisible to the triage queue it was filed for,",
          "and to the duplicate check the next merge runs).",
          "",
          "```bash",
          ...advisory,
          "```",
          "",
        ].join("\n");

  return fs
    .readFileSync(SETUP_TEMPLATE, "utf8")
    .replace("\n{{ADVISORY_LABELS}}\n", advisoryBlock)
    .replaceAll("{{PACKAGE}}", PACKAGE_NAME)
    // The npm scope on its own — `@owner` — which is what an `.npmrc` registry
    // line is keyed on, and the one substitution that is a *part* of the name
    // rather than the name.
    .replaceAll("{{SCOPE}}", PACKAGE_NAME.split("/")[0] ?? PACKAGE_NAME)
    .replaceAll("{{VERSION}}", VERSION)
    .replaceAll("{{SLUG}}", repoSlug(PACKAGE_NAME))
    .replaceAll("{{CALLERS}}", callers.join("\n"))
    .replaceAll("{{LABELS}}", labels.join("\n"));
};

const pinnedReference = (entry: string, file: string): string => {
  const { text, found } = rewritePins(fs.readFileSync(path.join(REFERENCE_DIR, entry), "utf8"), {
    packageName: PACKAGE_NAME,
    version: VERSION,
  });
  if (!found.includes("ref")) {
    throw new Error(
      `${entry} carries no \`uses:\` pin this version knows how to rewrite. Installing it would ` +
        `point an adopter at whichever release the reference happened to be written against.`,
    );
  }
  assertCoupled(text, file);
  return text;
};

/**
 * Move an installed caller's pin to this version, **in the adopter's own file**.
 *
 * Every other line of it is theirs — see the header. `rewritePins` matches a
 * `@v<major.minor.patch>` ref and nothing else, so a caller deliberately pinned
 * to a SHA, or wrongly pinned to a branch, is reported rather than converted:
 * the first is a choice this has no business overriding and the second is a
 * finding `doctor` already raises by name.
 */
const repin = (dir: string, file: string): InitChange => {
  const full = path.join(dir, ...file.split("/"));
  const { text, found } = rewritePins(fs.readFileSync(full, "utf8"), {
    packageName: PACKAGE_NAME,
    version: VERSION,
  });
  if (!found.includes("ref")) {
    return {
      file,
      action: "kept",
      note: `its \`uses:\` ref is not a \`@v<version>\` tag, so it is left exactly as pinned`,
    };
  }
  return { file, action: put(full, text) };
};

/**
 * Install the reference caller for `entry`, unless something already occupies
 * the filename. A file there that is not one of ours is an adopter's own
 * workflow that happens to share the name, and `put` would overwrite it and
 * report `updated` — the same silent reversion a re-run must not perform, with
 * a file this never wrote.
 */
const install = (dir: string, entry: string): InitChange => {
  const file = `${WORKFLOW_DIR}/${CALLER_PREFIX}${entry}`;
  const full = path.join(dir, ...file.split("/"));
  if (fs.existsSync(full)) {
    return {
      file,
      action: "kept",
      note: `a file of that name is already here and calls something else — rename it, or copy examples/callers/${entry} in by hand`,
    };
  }
  return { file, action: put(full, pinnedReference(entry, file)) };
};

/**
 * Pin what is installed, install what is not, and write the prompt for what is
 * left. Returns one entry per file considered, so a re-run that changed nothing
 * can be reported as such — and so every refusal is visible rather than being
 * the absence of a line.
 */
export const init = (options: InitOptions): readonly InitChange[] => {
  const { dir } = options;
  const installed = readInstalledCallers(dir, PACKAGE_NAME);

  // One entry per *file*, not per caller: two jobs of ours in one file is a
  // shape an adopter may well have, and it holds one pin rewrite between them.
  const files = [...new Set(installed.map((caller) => caller.file))];
  const changes: InitChange[] = files.map((file) => repin(dir, file));

  const present = new Set(installed.map((caller) => caller.workflow));
  const workflows = [...present];
  const callerFiles = [...files];

  for (const entry of referenceFiles()) {
    const name = entry.replace(/\.yml$/, "");
    if (present.has(name)) continue;

    // A first run scaffolds the lot. After that the subset is the adopter's
    // decision — a deleted caller stays deleted, and a workflow added in a
    // later release is named here rather than written into their tree behind
    // them, `pull_request_target` being what it is.
    if (installed.length > 0) {
      changes.push({
        file: `${WORKFLOW_DIR}/${CALLER_PREFIX}${entry}`,
        action: "kept",
        note: `no job here calls \`${name}\`; copy examples/callers/${entry} in and re-run to have it pinned`,
      });
      continue;
    }

    const change = install(dir, entry);
    changes.push(change);
    if (change.action === "kept") continue;

    workflows.push(name);
    callerFiles.push(change.file);
  }

  changes.push(putSetup(dir, workflows, callerFiles));

  const policy = allowPullRequestTarget(
    readInstalledCallers(dir, PACKAGE_NAME),
    options.github,
  );
  if (policy !== undefined) changes.push(policy);
  changes.push(...convergeLabels(workflows, options.labels));
  return changes;
};

/** How a label names itself in the list of changes. */
export const labelChange = (name: string): string => `label "${name}"`;

/**
 * Every label the loop owns, as `docs/ADOPTING.md` §3 defines it (#236): the
 * `agent:*` labels the installed callers reach for, and `agent:follow-ups`
 * whichever callers were taken, since the review adds it whether or not the
 * filing caller is installed. The triage labels beside them are a vocabulary of
 * their own and an adopter's, so they are named in `SETUP.md` and never
 * written here.
 */
const ownedLabels = (workflows: readonly string[]): readonly LabelSpec[] => [
  ...labelSpecsFor(workflows),
  ...Object.values(ADVISORY_LABELS)
    .flat()
    .filter((label) => label.name.startsWith("agent:")),
];

/**
 * Create a missing label, edit one whose colour or description differs, and
 * leave one that matches, so a second run reports every label `unchanged`.
 * Then delete each retired label that is still here, unless an open issue or
 * pull request carries it: that one is left, and the note says where it is.
 *
 * Never fails the install, for the policy step's reason: the callers are on
 * disk by now, and a token that cannot write a label leaves a step a human can
 * take, named with the command.
 */
const convergeLabels = (workflows: readonly string[], github: LabelSurface): readonly InitChange[] => {
  const wanted = ownedLabels(workflows);
  const present = github.labels();
  if (present === undefined) {
    return [
      {
        file: "labels",
        action: "kept",
        note:
          `could not list this repository's labels, so none was created or recoloured; ` +
          `run ${wanted.map(labelCommand).join(" && ")}`,
      },
    ];
  }

  const byName = new Map(present.map((label) => [label.name, label]));
  const changes: InitChange[] = wanted.map((label): InitChange => {
    const file = labelChange(label.name);
    const current = byName.get(label.name);
    if (current === undefined) {
      const refused = github.create(label);
      return refused === undefined
        ? { file, action: "created" }
        : { file, action: "kept", note: `GitHub refused to create it (${refused}); run ${labelCommand(label)}` };
    }
    // GitHub answers the colour in lower case whatever it was given.
    if (current.color.toLowerCase() === label.color.toLowerCase() && current.description === label.description) {
      return { file, action: "unchanged" };
    }
    const refused = github.edit(label);
    return refused === undefined
      ? { file, action: "updated", note: `colour and description as docs/ADOPTING.md §3 gives them` }
      : {
          file,
          action: "kept",
          note: `GitHub refused to edit it (${refused}); run gh label edit "${label.name}" --color ${label.color} --description "${label.description}"`,
        };
  });

  for (const name of RETIRED_LABELS) {
    if (!byName.has(name)) continue;
    const file = labelChange(name);
    const carriers = github.carriers(name);
    if (carriers === undefined) {
      changes.push({
        file,
        action: "kept",
        note: `retired, but whether an open issue or PR still carries it could not be read; once none does, run ${labelDeleteCommand(name)}`,
      });
      continue;
    }
    if (carriers.length > 0) {
      changes.push({
        file,
        action: "kept",
        note: `retired, but still on ${carriers.map((n) => `#${n}`).join(", ")}; once none of them carries it, run ${labelDeleteCommand(name)}`,
      });
      continue;
    }
    const refused = github.remove(name);
    changes.push(
      refused === undefined
        ? { file, action: "deleted", note: `retired, and no open issue or PR carried it` }
        : { file, action: "kept", note: `retired, but GitHub refused to delete it (${refused}); run ${labelDeleteCommand(name)}` },
    );
  }
  return changes;
};

/**
 * Let the callers keep running on a public repository once GitHub blocks
 * `pull_request_target` there by default (#219): an Actions event policy
 * allowing it for **the callers' files and nothing else**, so every other
 * workflow in the repository stays under the block. `setup/policies.ts` holds
 * the shape and why it is that shape.
 *
 * Idempotent: a policy already allowing it for every caller is `unchanged`,
 * whoever wrote it. One this wrote that is short of a caller added since is
 * extended in place rather than doubled. And it never fails the install: the
 * callers are on disk by now, and a token that cannot write the policy is a
 * step left to a human, named with the exact call and the settings page.
 *
 * A private or internal repository is outside the rule and hears nothing.
 */
const allowPullRequestTarget = (
  callers: readonly InstalledCaller[],
  github: PolicySurface,
): InitChange | undefined => {
  const triggered = triggeredFiles(callers);
  if (triggered.length === 0) return undefined;

  const byHand = (why: string, files: readonly string[]): InitChange => ({
    file: POLICY_CHANGE,
    action: "kept",
    note:
      `${why} GitHub blocks \`pull_request_target\` on a public repository from 2026-11-02 unless a ` +
      `policy allows it, and ${files.join(", ")} run on it. As a repository admin, run ` +
      `\`${policyCommand(policyBody(callers, files))}\`, or add it under ${POLICY_SETTINGS}`,
  });

  const visibility = github.visibility();
  if (visibility === "private") return undefined;
  if (visibility === undefined) {
    return byHand(`Could not read this repository's visibility; a private one needs nothing here.`, triggered);
  }

  const policies = github.policies();
  if (policies === undefined) return byHand(`Could not read this repository's Actions policies.`, triggered);

  const unallowed = unallowedFiles(callers, policies);
  if (unallowed.length === 0) {
    return { file: POLICY_CHANGE, action: "unchanged", note: `allows \`pull_request_target\` for ${triggered.join(", ")}` };
  }

  // One that could not be read may be the one allowing them, or this step's
  // own: creating a second beside it is a write on a fact nobody read.
  if (unreadable(policies)) {
    return byHand(`Could not read every Actions policy that applies to this repository.`, unallowed);
  }

  const ours = policies.find((policy) => policy?.name === POLICY_NAME && policy.id !== undefined);
  if (ours?.id !== undefined) {
    // Switched off, or to evaluate, by somebody: that is a decision, and
    // turning it back on behind them is the silent reversion a re-run must
    // never perform.
    if (ours.enforcement !== "active") {
      return {
        file: POLICY_CHANGE,
        action: "kept",
        note: `its enforcement is \`${ours.enforcement}\`, which allows nothing; set it to active under ${POLICY_SETTINGS} if that was not deliberate`,
      };
    }
    const files = [...new Set([...(ours.include ?? []), ...unallowed])].sort();
    const refused = github.update(ours.id, policyBody(callers, files, ours.allowedEvents ?? []));
    return refused === undefined
      ? { file: POLICY_CHANGE, action: "updated", note: `now allows \`pull_request_target\` for ${unallowed.join(", ")} too` }
      : byHand(`GitHub refused the update (${refused}).`, unallowed);
  }

  const refused = github.create(policyBody(callers, unallowed));
  return refused === undefined
    ? { file: POLICY_CHANGE, action: "created", note: `allows \`pull_request_target\` for ${unallowed.join(", ")} and no other workflow` }
    : byHand(`GitHub refused to create it (${refused}).`, unallowed);
};

/**
 * Whether `dir` is this package's own checkout (#238), by the name its
 * manifest declares. Its callers are real and pinned like anyone's, but the
 * setup prompt is an adopter's to-do list, and here it is a stray file at the
 * root of the repository that wrote it.
 */
const isOwnRepository = (dir: string): boolean => {
  try {
    const manifest: unknown = JSON.parse(fs.readFileSync(path.join(dir, "package.json"), "utf8"));
    return typeof manifest === "object" && manifest !== null && (manifest as { name?: unknown }).name === PACKAGE_NAME;
  } catch {
    return false;
  }
};

/**
 * The one file here that is not ours by construction. `SETUP.md` is a name an
 * adopter may already be using for something of their own, and overwriting a
 * document somebody wrote is not the same act as updating a caller this wrote —
 * so it carries a marker, and without it the file is left alone and reported.
 */
const putSetup = (
  dir: string,
  workflows: readonly string[],
  callers: readonly string[],
): InitChange => {
  if (isOwnRepository(dir)) {
    return {
      file: SETUP_FILE,
      action: "kept",
      note: `this is ${PACKAGE_NAME}'s own repository, and the setup prompt is for an adopter's`,
    };
  }
  const full = path.join(dir, SETUP_FILE);
  if (fs.existsSync(full) && !fs.readFileSync(full, "utf8").includes(setupMarker())) {
    return {
      file: SETUP_FILE,
      action: "kept",
      note: `not written by ${PACKAGE_NAME} — rename it and re-run to get the setup prompt`,
    };
  }
  return { file: SETUP_FILE, action: put(full, renderSetup(workflows, callers)) };
};
